"""Build the fixed evaluation set: eval/eval_set.jsonl (questions, gold answers, supporting titles, dev/test split).

Simple (one-paragraph) questions are generated ONCE by the LLM and saved in eval/generated_simple_questions.jsonl;
later runs reuse that file, because an LLM gives different output each time and the set must stay fixed.
Contradictory questions are added separately (task H2).

Usage (from the repository root; needs data/ from eval/build_dataset.py, and GEMINI_API_KEY the first time):
    .venv/bin/python eval/build_eval_set.py
"""
import json
import random
import sys
from pathlib import Path

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPOSITORY_ROOT / "backend"))  # lets this script import the casefile package

from casefile.config import get_settings  # noqa: E402
from casefile.evaluation.eval_set import (EVAL_SEED, SIMPLE_COUNT, assign_splits, build_unanswerable_items,  # noqa: E402
                                          pick_simple_paragraphs, sample_hotpot_questions)
from casefile.rag.agent import extract_json_object  # noqa: E402
from casefile.rag.llm import GeminiProvider, Message  # noqa: E402

DATA_FOLDER = REPOSITORY_ROOT / "data"
EVAL_SET_FILE = REPOSITORY_ROOT / "eval" / "eval_set.jsonl"
GENERATED_SIMPLE_FILE = REPOSITORY_ROOT / "eval" / "generated_simple_questions.jsonl"

SIMPLE_QUESTION_PROMPT = """Write ONE factual question that can be answered from this paragraph alone, plus its answer.
Rules: the question must name its subject (no "this paragraph", "the film above"); the answer must be short
(a name, number, date or a few words) and copied from the paragraph. Reply with ONLY: {"question": "...", "answer": "..."}"""


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def write_jsonl(records: list[dict], path: Path) -> None:
    path.write_text("".join(json.dumps(record, ensure_ascii=False) + "\n" for record in records), encoding="utf-8")


def generate_simple_questions(paragraphs: list[dict]) -> list[dict]:
    settings = get_settings()
    llm = GeminiProvider(settings.gemini_api_key, settings.gemini_model, settings.llm_timeout_seconds,
                         requests_per_minute=settings.llm_requests_per_minute)
    generated = []
    for number, paragraph in enumerate(paragraphs, start=1):
        reply = llm.generate(SIMPLE_QUESTION_PROMPT, [Message(role="user", text=f"Title: {paragraph['title']}\n\n"
                                                                              f"{paragraph['text']}")], tools=[])
        question_and_answer = extract_json_object(reply.text)
        generated.append({"id": f"simple-{number:02d}", "category": "simple",
                          "question": str(question_and_answer["question"]), "answer": str(question_and_answer["answer"]),
                          "supporting_titles": [paragraph["title"]], "source": "generated by the LLM, checked by hand"})
        print(f"  generated simple-{number:02d} from '{paragraph['title']}'", flush=True)
    return generated


def main() -> None:
    random_generator = random.Random(EVAL_SEED)
    questions = read_jsonl(DATA_FOLDER / "questions.jsonl")
    hotpot_items = sample_hotpot_questions(questions, random_generator)

    if GENERATED_SIMPLE_FILE.exists():
        simple_items = read_jsonl(GENERATED_SIMPLE_FILE)
        print(f"Reusing {len(simple_items)} simple questions from {GENERATED_SIMPLE_FILE.name}")
    else:
        used_titles = {title for item in hotpot_items for title in item["supporting_titles"]}
        paragraphs = pick_simple_paragraphs(read_jsonl(DATA_FOLDER / "corpus.jsonl"), SIMPLE_COUNT, random_generator,
                                            used_titles)
        print(f"Generating {SIMPLE_COUNT} simple questions with the LLM (one time only)...")
        simple_items = generate_simple_questions(paragraphs)
        write_jsonl(simple_items, GENERATED_SIMPLE_FILE)

    # Splits use their own seeded generator, so reusing the simple-question file can't change them.
    eval_items = assign_splits(hotpot_items + simple_items + build_unanswerable_items(), random.Random(EVAL_SEED))
    write_jsonl(eval_items, EVAL_SET_FILE)

    print(f"\nWrote {len(eval_items)} questions to {EVAL_SET_FILE.relative_to(REPOSITORY_ROOT)}")
    for category in ("bridge", "comparison", "simple", "unanswerable"):
        items = [item for item in eval_items if item["category"] == category]
        dev_count = sum(item["split"] == "dev" for item in items)
        print(f"  {category:<13} {len(items):>3}  (dev {dev_count}, test {len(items) - dev_count})")


if __name__ == "__main__":
    main()
